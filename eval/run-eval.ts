// Runs the eval set without any API key and writes eval/results.md.
// Exits 1 if hit@3 < 0.8 or refusal accuracy < 0.8.
// Usage: npm run eval

import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { createAsker, loadIndex } from '../src/answer.ts';
import { EMBEDDING_MODEL, QUESTIONS_PATH, REFUSAL_THRESHOLD, ROOT, TOP_K } from '../src/config.ts';
import { embed } from '../src/embedder.ts';
import { computeMetrics, loadQuestions, thresholdSweep, type EvalResult } from '../src/eval.ts';

const MIN_HIT_AT_3 = 0.8;
const MIN_REFUSAL = 0.8;

const pct = (x: number) => `${(x * 100).toFixed(0)}%`;

async function main() {
  const questions = await loadQuestions(QUESTIONS_PATH);
  const index = await loadIndex();
  // No `gemini` here on purpose: the eval must be deterministic and must not need a key.
  const { ask, retrieve } = createAsker({ index, embed });

  const results: EvalResult[] = [];
  for (const q of questions) {
    const { hits } = await retrieve(q.question);
    const answer = await ask(q.question);
    results.push({
      q,
      retrievedPaths: hits.map((h) => h.chunk.path),
      topScore: hits[0]?.score ?? 0,
      grounded: answer.grounded,
    });
  }

  const m = computeMetrics(results);
  const sweep = thresholdSweep(results, [0.4, 0.45, 0.5, 0.55, 0.6, 0.61, 0.62, 0.63, 0.64, 0.65, 0.7, 0.75]);
  const pass = m.hitAt3 >= MIN_HIT_AT_3 && m.refusalAccuracy >= MIN_REFUSAL;

  const rows = results.map((r) => {
    const ok = r.q.answerable ? r.retrievedPaths.includes(r.q.expected_path!) : !r.grounded;
    const expected = r.q.answerable ? `\`${r.q.expected_path}\`` : '(refuse)';
    return `| ${r.q.id} | ${r.q.question} | ${expected} | ${r.topScore.toFixed(3)} | ${r.grounded ? 'answered' : 'refused'} | ${ok ? 'yes' : 'NO'} |`;
  });

  const md = [
    '# Eval results',
    '',
    `Generated by \`npm run eval\`. Model \`${EMBEDDING_MODEL}\`, top-k ${TOP_K}, refusal threshold ${REFUSAL_THRESHOLD}, no API key.`,
    '',
    '| Metric | Value |',
    '|---|---|',
    `| Retrieval hit@3 (answerable, n=${m.answerable}) | ${m.hitAt3.toFixed(2)} (${pct(m.hitAt3)}) |`,
    `| Refusal accuracy (unanswerable, n=${m.unanswerable}) | ${m.refusalAccuracy.toFixed(2)} (${pct(m.refusalAccuracy)}) |`,
    `| Answered rate (answerable, n=${m.answerable}) | ${m.answeredRate.toFixed(2)} (${pct(m.answeredRate)}) |`,
    `| Gate (hit@3 >= ${MIN_HIT_AT_3} and refusal >= ${MIN_REFUSAL}) | ${pass ? 'PASS' : 'FAIL'} |`,
    '',
    '"Answered rate" is not gated. It shows how many answerable questions were wrongly refused.',
    '',
    '## Per question',
    '',
    '| id | question | expected page | top score | result | correct |',
    '|---|---|---|---|---|---|',
    ...rows,
    '',
    '## Threshold sweep',
    '',
    'How the refusal threshold was chosen: for each candidate, the share of answerable questions that',
    'would still be answered and the share of unanswerable questions that would be refused.',
    'The threshold is calibrated on these same 20 questions, so treat it as a starting point, not a',
    'held-out result.',
    '',
    '| threshold | answerable answered | unanswerable refused |',
    '|---|---|---|',
    ...sweep.map((s) => `| ${s.threshold.toFixed(2)} | ${pct(s.answered)} | ${pct(s.refused)} |`),
    '',
  ].join('\n');

  await writeFile(join(ROOT, 'eval', 'results.md'), md, 'utf8');

  console.log(`hit@3            ${m.hitAt3.toFixed(2)}  (${m.answerable} answerable)`);
  console.log(`refusal accuracy ${m.refusalAccuracy.toFixed(2)}  (${m.unanswerable} unanswerable)`);
  console.log(`answered rate    ${m.answeredRate.toFixed(2)}`);
  for (const r of results) {
    const ok = r.q.answerable ? r.retrievedPaths.includes(r.q.expected_path!) : !r.grounded;
    console.log(`  ${ok ? 'ok ' : 'BAD'} ${r.q.id} top=${r.topScore.toFixed(3)} ${r.retrievedPaths.join(', ')}`);
  }
  console.log(`Wrote eval/results.md -> ${pass ? 'PASS' : 'FAIL'}`);
  if (!pass) process.exitCode = 1;
}

await main();
